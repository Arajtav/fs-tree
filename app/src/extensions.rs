pub fn get_color_from_extension(extension: &OsStr) -> [f32; 3] {
    let ext_str = match extension.to_str() {
        Some(s) => s.to_ascii_lowercase(),
        None => return [0.5, 0.5, 0.5],
    };

    MAP.get(ext_str.as_bytes())
        .copied()
        .unwrap_or([0.5, 0.5, 0.5])
}
